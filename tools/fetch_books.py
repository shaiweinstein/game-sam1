def load_shelf_books(books_root: Path) -> tuple[list[dict], list[str]]:
    """Every ``library/books/{id}/book.json``, sorted by ``shelfOrder`` (1..n)."""
    books: list[dict] = []
    errors: list[str] = []
    for bj_path in sorted(books_root.glob("*/book.json")):
        label = f"book {bj_path.parent.name}"
        try:
            data = json.loads(bj_path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as err:
            errors.append(f"{label}: book.json unreadable: {err}")
            continue
        missing = [k for k in BOOK_REQUIRED if k not in data]
        if missing:
            errors.append(f"{label}: book.json missing field(s): {', '.join(missing)}")
            continue
        if str(data["id"]) != bj_path.parent.name:
            errors.append(f"{label}: id {data['id']} != directory name {bj_path.parent.name}")
        pages = data.get("pages") or []
        if data.get("pageCount") != len(pages):
            errors.append(f"{label}: pageCount {data.get('pageCount')} != {len(pages)} pages")
        # license-aware attribution rule: CC BY books must name CC BY; the
        # public-domain Beatrix Potter books must name "public domain".
        license_name = str(data.get("license") or "")
        attribution = str(data.get("attribution") or "")
        if license_name.startswith("CC BY"):
            if "CC BY" not in attribution:
                errors.append(f"{label}: attribution does not contain 'CC BY'")
        elif license_name == "Public Domain":
            if "public domain" not in attribution.lower():
                errors.append(f"{label}: attribution does not contain 'public domain'")
        else:
            errors.append(f"{label}: unsupported license {license_name!r}")
        if not valid_jpeg(bj_path.parent / "thumb.jpg"):
            errors.append(f"{label}: thumb.jpg missing or not a valid JPEG")
        for page in pages:
            image = str(page.get("image") or "")
            if image and not (bj_path.parent / image).is_file():
                errors.append(f"{label}: referenced {image} is missing on disk")
        data.setdefault("illustrators", [])
        books.append(data)
    try:
        books.sort(key=lambda d: int(d["shelfOrder"]))
    except (TypeError, ValueError) as err:
        errors.append(f"shelfOrder not an int somewhere: {err}")
        return books, errors
    orders = [int(d["shelfOrder"]) for d in books]
    if orders != list(range(1, len(books) + 1)):
        errors.append(f"shelfOrder not contiguous 1..{len(books)}: {orders}")
    return books, errors


def manifest_entry(book: dict) -> dict:
    """One library/manifest.json entry; every field present, paths from library/."""
    book_id = int(book["id"])
    return {
        "id": book_id,
        "shelfOrder": int(book["shelfOrder"]),
        "title": str(book["title"]),
        "level": int(book["level"]),
        "pageCount": int(book["pageCount"]),
        "authors": list(book.get("authors") or []),
        "illustrators": list(book.get("illustrators") or []),
        "thumb": f"books/{book_id}/thumb.jpg",
        "book": f"books/{book_id}/book.json",
        "sourceUrl": str(book["sourceUrl"]),
        "license": str(book["license"]),
    }


def build_manifest(books: list[dict]) -> dict:
    licenses: list[str] = []
    for book in books:  # first-seen (shelf) order: ["CC BY 4.0", "Public Domain"]
        name = str(book.get("license") or "")
        if name not in licenses:
            licenses.append(name)
    return {
        "licenses": licenses,
        "source": MANIFEST_SOURCE,
        "count": len(books),
        "books": [manifest_entry(b) for b in books],
    }


def book_has_audio(book: dict) -> bool:
    """True when any page carries a stamped ``audio`` path."""
    return any(str(p.get("audio") or "") for p in book.get("pages") or [])


def name_join(names) -> str:
    return ", ".join(str(n) for n in names) if names else "(none)"


def cc_by_line(book: dict) -> str:
    """The standard CC BY attribution pattern for one book."""
    illustrators = book.get("illustrators") or []
    ill_part = f", illustrated by {name_join(illustrators)}" if illustrators else ""
    return (
        f'"{book["title"]}" by {name_join(book.get("authors") or [])}{ill_part}. '
        f'© {book.get("publishedYear")} {book.get("publisher")}. '
        f'Source: {book["sourceUrl"]}. License: {LICENSE} ({LICENSE_URL}). '
        f"Used unmodified; only image resolution differs."
    )


def credits_entry(n: int, book: dict) -> str:
    lines = [
        f'## {n}. {book["title"]} (id {book["id"]})',
        "",
        f'- **title:** {book["title"]}',
        f'- **authors:** {name_join(book.get("authors") or [])}',
        f'- **illustrators:** {name_join(book.get("illustrators") or [])}',
        f'- **publishedYear:** {book.get("publishedYear")}',
        f'- **publisher:** {book.get("publisher")}',
        f'- **sourceUrl:** {book["sourceUrl"]}',
        f"- **license:** {LICENSE} ({LICENSE_URL})",
        "",
        textwrap.fill(
            "CC BY attribution: " + cc_by_line(book),
            width=78,
            break_long_words=False,
            break_on_hyphens=False,
        ),
        "",
        f"Verbatim `attribution` text from `library/books/{book['id']}/book.json`:",
        "",
        f'> {book["attribution"]}',
        "",
    ]
    if book_has_audio(book):
        lines[-1:-1] = ["", audio_credits_line()]
    return "\n".join(lines)


def pd_credits_section(books: list[dict]) -> str:
    """The "Public domain — Beatrix Potter (Project Gutenberg)" credits block."""
    lines = [
        "## Public domain — Beatrix Potter (Project Gutenberg)",
        "",
        textwrap.fill(
            "The following public-domain titles complete the shelf. Each was "
            "written and illustrated by Beatrix Potter (Frederick Warne & Co., "
            "first published 1902-1909) and is public domain in the USA; the "
            "text and its illustrations come from Project Gutenberg.",
            width=78,
            break_long_words=False,
            break_on_hyphens=False,
        ),
        "",
    ]
    for i, book in enumerate(books, start=1):
        pg_id = book["id"]
        lines += [
            f'{i}. **{book["title"]}** ({book.get("publishedYear")}) — '
            f"Project Gutenberg eBook #{pg_id}: "
            f"https://www.gutenberg.org/ebooks/{pg_id}",
            textwrap.fill(
                f"Text and illustrations by Beatrix Potter, public domain in "
                f"the USA, source Project Gutenberg eBook #{pg_id}.",
                width=78,
                initial_indent="   ",
                subsequent_indent="   ",
                break_long_words=False,
                break_on_hyphens=False,
            ),
        ]
        if book_has_audio(book):
            lines += ["", "   " + audio_credits_line()]
        lines += [""]
    return "\n".join(lines) + "\n"


def credits_markdown(books: list[dict]) -> str:
    cc_books = [b for b in books if str(b.get("license") or "").startswith("CC BY")]
    pd_books = [b for b in books if str(b.get("license") or "") == "Public Domain"]
    head = [
        "# Library storybook credits",
        "",
        textwrap.fill(
            f"The StoryWeaver storybooks in `library/books/` are content "
            f"licensed {LICENSE} from {MANIFEST_SOURCE} ({MANIFEST_SOURCE_HOME}). "
            f"License: {LICENSE_URL}. In short: storybooks are used unmodified; "
            f"only image resolution differs. The shelf also holds public-domain "
            f"Beatrix Potter titles from Project Gutenberg (their section is at "
            f"the end).",
            width=78,
            break_long_words=False,
            break_on_hyphens=False,
        ),
        "",
        textwrap.fill(
            "One entry per CC BY 4.0 book follows, in shelf order: the standard "
            "CC BY attribution pattern and, below it, the verbatim `attribution` "
            "text carried in that book's book.json (the verbatim block names the "
            "actual rightsholders -- some titles credit Room to Read, not "
            "Pratham Books).",
            width=78,
            break_long_words=False,
            break_on_hyphens=False,
        ),
        "",
        "",
    ]
    entries = [credits_entry(i, b) for i, b in enumerate(cc_books, start=1)]
    out = "\n".join(head) + "\n".join(entries)
    if pd_books:
        out += "\n" + pd_credits_section(pd_books)
    return out


def upsert_notices_section(notices_path: Path, heading: str, section: str) -> str:
    """Append one notices section at the end of THIRD-PARTY-NOTICES.md.

    Re-runs replace the previously appended section in place so regeneration
    never duplicates it and never touches the rest of the file (including a
    sibling section appended after it).
    Returns "appended", "replaced" or "unchanged".
    """
    body = notices_path.read_text(encoding="utf-8")
    m = re.search(rf"^{re.escape(heading)}$", body, re.MULTILINE)
    if m is None:
        notices_path.write_text(body.rstrip("\n") + "\n\n" + section, encoding="utf-8")
        return "appended"
    start = m.start()
    if start >= 5 and body[start - 5 : start] == "---\n\n":
        start -= 5  # the section's own --- separator came along on append
    nxt = re.search(r"^## ", body[m.end() :], re.MULTILINE)
    end = m.end() + nxt.start() if nxt else len(body)
    if nxt is not None and end >= 5 and body[end - 5 : end] == "---\n\n":
        end -= 5  # the NEXT section's separator belongs to that section
    if body[start:end].rstrip("\n") == section.rstrip("\n"):
        return "unchanged"
    notices_path.write_text(body[:start] + section + body[end:], encoding="utf-8")
    return "replaced"


def cmd_manifest(args: argparse.Namespace) -> int:
    books_root = Path(args.out)
    if not books_root.is_dir():
        print(f"error: library books dir not found: {books_root}", file=sys.stderr)
        return 2
    books, errors = load_shelf_books(books_root)
    if errors:
        print(f"== fetch_books.py manifest: {len(errors)} error(s), nothing written ==")
        for err in errors:
            print(f"  ! {err}")
        return 1

    library_dir = books_root.parent
    manifest_path = library_dir / "manifest.json"
    credits_path = library_dir / "CREDITS.md"
    notices_path = Path(args.notices)

    manifest = build_manifest(books)
    manifest_path.write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    credits_path.write_text(credits_markdown(books), encoding="utf-8")
    notices_action = upsert_notices_section(
        notices_path, NOTICES_HEADING, NOTICES_SECTION)
    pg_notices_action = upsert_notices_section(
        notices_path, PG_NOTICES_HEADING, PG_NOTICES_SECTION)

    print("== fetch_books.py manifest -- final report ==")
    print(f"books read         : {len(books)} (from {books_root})")
    print(f"manifest           : {manifest_path} (count {manifest['count']})")
    print(f"credits            : {credits_path}")
    print(f"notices            : {notices_path} ({notices_action}, "
          f"pg {pg_notices_action})")
    print()
    for book in books:
        entry = manifest_entry(book)
        print(f'{entry["shelfOrder"]:2d}. id {entry["id"]} -- {entry["title"]} '
              f'({entry["pageCount"]} pages)')
    print()
    print("validation: OK (required fields, dir==id, pageCount==len(pages), "
          "attribution license-aware, thumb JPEG, page files present, "
          "shelfOrder 1..n)")
    return 0


