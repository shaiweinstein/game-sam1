def search_url(page: int, per_page: int, levels: list[str] | None = None) -> str:
    """Build a books-search URL. Keys keep the ``[]`` suffix the API expects."""
    params: list[tuple[str, str]] = [
        ("languages[]", "English"),
        ("sort", "Most Read"),
        ("page", str(page)),
        ("per_page", str(per_page)),
    ]
    for lv in levels or []:
        params.append(("levels[]", str(lv)))
    return f"{API_BASE}/books-search?{urllib.parse.urlencode(params)}"


def story_url(book_id) -> str:
    return f"{API_BASE}/stories/{book_id}"


def reads_of(book: dict) -> int:
    try:
        return int(book.get("readsCount") or 0)
    except (TypeError, ValueError):
        return 0


def likes_of(book: dict) -> int:
    try:
        return int(book.get("likesCount") or 0)
    except (TypeError, ValueError):
        return 0


def level_of(book: dict) -> str:
    return str(book.get("level") or "").strip()


def is_gif(book: dict) -> bool:
    return book.get("isGif") in (True, 1, "1", "true", "True")


def name_list(value) -> list[str]:
    """Normalize authors[]/illustrators[] entries to a list of strings."""
    out: list[str] = []
    for item in value or []:
        if isinstance(item, str):
            out.append(item.strip())
        elif isinstance(item, dict):
            out.append(str(item.get("name") or item.get("title") or "").strip())
        else:
            out.append(str(item).strip())
    return [n for n in out if n]


def cover_thumb_url(book: dict) -> str | None:
    """Smallest available cover size (thumb is fine for the curation sheet)."""
    sizes = ((book.get("coverImage") or {}).get("sizes")) or []
    scored: list[tuple[int, str]] = []
    for size in sizes:
        url = size.get("url")
        if not url:
            continue
        try:
            width = int(size.get("width") or 0)
        except (TypeError, ValueError):
            width = 0
        scored.append((width if width > 0 else 10**9, url))
    if not scored:
        return None
    scored.sort(key=lambda pair: pair[0])
    return scored[0][1]


def one_line(text: str | None, limit: int = 90) -> str:
    """Whitespace-collapse, entity-unescape, truncate to ~90 chars for the MD."""
    flat = html.unescape(re.sub(r"\s+", " ", text or "")).strip()
    if len(flat) <= limit:
        return flat
    cut = flat[: limit - 1].rsplit(" ", 1)[0] or flat[: limit - 1]
    return cut + "..."


def md_cell(text: str | None) -> str:
    """Make a string safe for a markdown table cell."""
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


