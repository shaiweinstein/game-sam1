class Fetcher:
    """Sequential urllib GETs: polite UA, 20 s timeout, one retry, disk cache."""

    def __init__(self, use_cache: bool = True) -> None:
        self.use_cache = use_cache
        self.total_bytes = 0
        self.requests = 0
        self.cache_hits = 0
        OUT_DIR.mkdir(parents=True, exist_ok=True)
        if use_cache:
            CACHE_DIR.mkdir(parents=True, exist_ok=True)

    def _cache_path(self, url: str) -> Path:
        digest = hashlib.sha256(url.encode("utf-8")).hexdigest()[:24]
        return CACHE_DIR / f"{digest}.json"

    def get_text(self, url: str, headers: dict | None = None) -> str:
        """GET ``url`` and return the body as text (cached across runs)."""
        cpath = self._cache_path(url)
        if self.use_cache and cpath.exists():
            try:
                self.cache_hits += 1
                return json.loads(cpath.read_text(encoding="utf-8"))["body"]
            except (OSError, ValueError, KeyError):
                pass  # corrupt cache entry -> refetch

        last_err: Exception | None = None
        for attempt in (1, 2):
            try:
                req_headers = {"User-Agent": USER_AGENT}
                if headers:
                    req_headers.update(headers)
                req = urllib.request.Request(url, headers=req_headers)
                with urllib.request.urlopen(req, timeout=TIMEOUT_S) as resp:
                    body = resp.read()
                self.requests += 1
                self.total_bytes += len(body)
                text = body.decode("utf-8", errors="replace")
                if self.use_cache:
                    cpath.write_text(
                        json.dumps({"url": url, "body": text}), encoding="utf-8"
                    )
                return text
            except Exception as err:  # URLError / HTTPError / TimeoutError / ...
                last_err = err
                print(f"  ! fetch attempt {attempt} failed: {url}: {err}", file=sys.stderr)
                if attempt == 1:
                    time.sleep(1.0)
        raise RuntimeError(f"fetch failed after retry: {url}: {last_err}")

    def get_json(self, url: str, headers: dict | None = None) -> dict:
        return json.loads(self.get_text(url, headers=headers))

    def _cache_path_bin(self, url: str) -> Path:
        digest = hashlib.sha256(url.encode("utf-8")).hexdigest()[:24]
        return CACHE_DIR / f"{digest}.bin"

    def get_bytes(self, url: str, headers: dict | None = None) -> bytes:
        """GET ``url`` and return raw bytes (cached across runs, like get_text)."""
        cpath = self._cache_path_bin(url)
        if self.use_cache and cpath.exists():
            try:
                body = cpath.read_bytes()
            except OSError:
                body = b""
            if body:
                self.cache_hits += 1
                return body

        last_err: Exception | None = None
        for attempt in (1, 2):
            try:
                req_headers = {"User-Agent": USER_AGENT}
                if headers:
                    req_headers.update(headers)
                req = urllib.request.Request(url, headers=req_headers)
                with urllib.request.urlopen(req, timeout=TIMEOUT_S) as resp:
                    body = resp.read()
                self.requests += 1
                self.total_bytes += len(body)
                if self.use_cache:
                    cpath.write_bytes(body)
                return body
            except Exception as err:  # URLError / HTTPError / TimeoutError / ...
                last_err = err
                print(f"  ! fetch attempt {attempt} failed: {url}: {err}", file=sys.stderr)
                if attempt == 1:
                    time.sleep(1.0)
        raise RuntimeError(f"fetch failed after retry: {url}: {last_err}")

    def stats(self) -> str:
        mb = self.total_bytes / (1024.0 * 1024.0)
        return (
            f"{self.requests} requests, {self.total_bytes:,} bytes ({mb:.2f} MiB), "
            f"{self.cache_hits} cache hits"
        )


