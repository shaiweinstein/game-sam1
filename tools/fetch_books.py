LIBRARY_DEFAULT = Path(__file__).resolve().parent.parent / "library" / "books"

XHR_HEADERS = {
    "Accept": "text/javascript, application/javascript, */*",
    "X-Requested-With": "XMLHttpRequest",
}

LICENSE = "CC BY 4.0"
LICENSE_URL = "https://creativecommons.org/licenses/by/4.0/"

# Attribution / credits blocks inside the pages payload (CC BY compliance).
CREDIT_CLASSES = frozenset(
    {
        "attrb-full",
        "attribution-text",
        "story-attribution-section",
        "other-credits-section",
        "illustration-attributions-section",
    }
)

JPEG_MAGIC = b"\xff\xd8"
JPEG_MIN_BYTES = 2048  # "every JPEG starts with FFD8 and > 2KB"

# reimage cap: "300KB" in the 1 KB = 1024 B convention of JPEG_MIN_BYTES above
REIMAGE_MAX_BYTES = 300 * 1024
REIMAGE_LADDER = ("size7", "size6", "size5")

SIZE_SRC_KEYS = (
    "data-size7-src",
    "data-size6-src",
    "data-size5-src",
    "data-size4-src",
    "data-size3-src",
    "data-size2-src",
    "data-size1-src",
)


def class_tokens(tag: str) -> set[str]:
    m = re.search(r"""class\s*=\s*['"]([^'"]*)['"]""", tag)
    return set(m.group(1).split()) if m else set()


def extract_reader_html(payload: str) -> str:
    """Pull the HTML out of ``$('#storyReader').html("...")`` and JS-unescape it.

    Verified escape recipe (order matters): ``\\"`` first, then ``\\'``, then
    ``\\/`` -- ONLY THEN run HTML regexes over the result.
    """
    m = re.search(r"\.html\(\s*\"", payload)
    if not m:
        raise RuntimeError("pages payload: $('#storyReader').html(\"...\") wrapper not found")
    start = m.end()
    # scan to the closing unescaped double quote of the JS string
    j = start
    while j < len(payload):
        if payload[j] == "\\":
            j += 2
            continue
        if payload[j] == '"':
            break
        j += 1
    content = payload[start:j]
    content = content.replace(r"\"", '"').replace(r"\'", "'").replace(r"\/", "/")
    return content


def element_inner_span(doc: str, open_end: int, is_div: bool) -> tuple[int, int]:
    """(start, end) of the inner HTML of the element whose open tag ends at open_end."""
    if is_div:
        depth = 1
        for t in re.finditer(r"<div\b[^>]*>|</div>", doc[open_end:]):
            if t.group(0).startswith("</"):
                depth -= 1
                if depth == 0:
                    return open_end, open_end + t.start()
            else:
                depth += 1
        return open_end, len(doc)
    end = doc.find("</p>", open_end)
    return open_end, (end if end != -1 else len(doc))


def strip_tags(fragment: str) -> str:
    """Tags stripped + html.unescape + whitespace collapsed (text extraction)."""
    fragment = re.sub(r"(?is)<(script|style)\b.*?</\1>", " ", fragment)
    # keep word gaps where block-level tags used to sit
    fragment = re.sub(r"(?i)</?(p|div|br|li|tr|h[1-6])\b[^>]*>", " ", fragment)
    fragment = re.sub(r"<[^>]+>", "", fragment)
    return re.sub(r"\s+", " ", html.unescape(fragment)).strip()


def drop_nested_spans(spans: list[tuple[int, int, str]]) -> list[tuple[int, int, str]]:
    """Keep outermost (start, end, text) spans only, in document order."""
    kept: list[tuple[int, int, str]] = []
    for start, end, text in sorted(spans, key=lambda c: (c[0], -c[1])):
        if any(s <= start and end <= e for s, e, _ in kept):
            continue
        kept.append((start, end, text))
    kept.sort(key=lambda c: c[0])
    return kept


def split_page_containers(html_doc: str) -> list[str]:
    """Split the reader HTML into its ``story-page`` containers (payload order)."""
    starts = [m.start() for m in re.finditer(
        r"<div\b[^>]*class=['\"][^'\"]*\bstory-page\b[^'\"]*['\"][^>]*>", html_doc
    )]
    spans = [(starts[i], starts[i + 1] if i + 1 < len(starts) else len(html_doc))
             for i in range(len(starts))]
    return [html_doc[a:b] for a, b in spans]


def container_content_texts(container: str) -> str:
    """Textbox text of one page: every ``content``/``newStories`` div joined with a space."""
    spans: list[tuple[int, int, str]] = []
    for m in re.finditer(r"<div\b[^>]*>", container):
        toks = class_tokens(m.group(0))
        if "content" not in toks and "newStories" not in toks:
            continue
        a, b = element_inner_span(container, m.end(), True)
        spans.append((a, b, strip_tags(container[a:b])))
    texts = [t for _, _, t in drop_nested_spans(spans)]
    return re.sub(r"\s+", " ", " ".join(texts)).strip()


def container_image_url(container: str) -> str | None:
    """size7 image url of one page block (falls back to smaller sizes)."""
    for m in re.finditer(r"<img\b[^>]*>", container):
        tag = m.group(0)
        if "responsive_illustration" not in class_tokens(tag):
            continue
        for key in SIZE_SRC_KEYS:
            am = re.search(re.escape(key) + r"""\s*=\s*['"]([^'"]+)['"]""", tag)
            if am:
                return am.group(1)
        am = re.search(r"""(?<![\w-])src\s*=\s*['"]([^'"]+)['"]""", tag)
        if am:
            return am.group(1)
    return None


def container_image_size_urls(container: str) -> dict[str, str]:
    """``sizeN`` -> url for one page block's ``responsive_illustration`` img.

    All ``data-sizeN-src`` ladder steps the payload carries (usually size1..7);
    empty dict for a numbered text-only page (no illustration).
    """
    out: dict[str, str] = {}
    for m in re.finditer(r"<img\b[^>]*>", container):
        tag = m.group(0)
        if "responsive_illustration" not in class_tokens(tag):
            continue
        for key in SIZE_SRC_KEYS:
            am = re.search(re.escape(key) + r"""\s*=\s*['"]([^'"]+)['"]""", tag)
            if am:
                out[key[len("data-") : -len("-src")]] = am.group(1)
        if out:
            return out
    return out


def size_variant_url(url: str, step: str) -> str | None:
    """Same crop hash, different ladder step: ``.../size7/{hash}.jpg`` -> ``step``.

    Returns None when the url carries no ``/sizeN/`` ladder segment.
    """
    if not re.search(r"/size[1-7]/", url):
        return None
    return re.sub(r"/size[1-7]/", f"/{step}/", url)


def container_is_story_page(container: str) -> bool:
    """True for numbered book pages (``fc_`` front cover / ``sp_`` story pages).

    ``bic_`` (credits / back-inside-cover) and ``bc_`` (back cover) blocks are
    unnumbered end-matter: the payload's own ``page_number`` divs number only
    fc/sp pages (``2/10`` ... ``10/10``, front cover implied as page 1) and
    metadata ``lastPagePosition`` counts exactly those.
    """
    m = re.search(r"""class=['"]((?:fc|sp|bic|bc)_)""", container)
    if m:
        return m.group(1) in ("fc_", "sp_")
    return bool(re.search(r"""class=["'][^"']*\bpage_number\b""", container))


def extract_attribution(html_doc: str) -> str:
    """Verbatim (tags stripped) credits text from the payload's attribution blocks."""
    spans: list[tuple[int, int, str]] = []
    for m in re.finditer(r"<(?:div|p)\b[^>]*>", html_doc):
        tag = m.group(0)
        if not (class_tokens(tag) & CREDIT_CLASSES):
            continue
        is_div = tag.startswith("<div")
        a, b = element_inner_span(html_doc, m.end(), is_div)
        spans.append((a, b, strip_tags(html_doc[a:b])))
    texts: list[str] = []
    seen: set[str] = set()
    for _, _, text in drop_nested_spans(spans):
        if text and text not in seen:
            seen.add(text)
            texts.append(text)
    return re.sub(r"\s+", " ", " ".join(texts)).strip()


def parse_published_year(
    attribution: str, copyright_notice: str, published_date: str
) -> tuple[str, str]:
    """(year, source) for ``publishedYear``.

    The rule is the credits' ``© Pratham Books, YYYY`` line (the metadata
    copyrightNotice field is yearless on StoryWeaver; the © line lives in the
    attribution blocks). Some books credit other rightsholders
    (``© Room to Read, YYYY``, ``The © for this translation lies with ...``),
    so the © holder is matched loosely -- the year CC BY requires displaying
    must be the year stored in ``publishedYear``. Falls back to publishedDate.
    """
    pratham = re.compile(r"©\s*Pratham\s*Books[^0-9]{0,20}((?:19|20)\d{2})")
    any_holder = re.compile(r"©[^0-9]{0,60}((?:19|20)\d{2})")
    for pat, label in ((pratham, "© Pratham Books line"), (any_holder, "© line")):
        for text, where in ((copyright_notice, "copyrightNotice"), (attribution, "attribution")):
            m = pat.search(text or "")
            if m:
                return m.group(1), f"{label} in {where}"
    m = re.search(r"\b((?:19|20)\d{2})\b", published_date or "")
    if m:
        return m.group(1), "publishedDate"
    return "", "none"


def valid_jpeg(path: Path) -> bool:
    try:
        data = path.read_bytes()
    except OSError:
        return False
    return data.startswith(JPEG_MAGIC) and len(data) > JPEG_MIN_BYTES


def parse_id_list(raw: str) -> list[int]:
    out: list[int] = []
    for part in raw.replace(" ", "").split(","):
        if part:
            out.append(int(part))
    return out


def book_complete(book_dir: Path) -> bool:
    """Resume marker: book.json present and every JPEG it references is valid."""
    bj_path = book_dir / "book.json"
    if not bj_path.exists():
        return False
    try:
        data = json.loads(bj_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return False
    pages = data.get("pages") or []
    if not pages or len(pages) != data.get("pageCount"):
        return False
    if not valid_jpeg(book_dir / "thumb.jpg"):
        return False
    for page in pages:
        image = str(page.get("image") or "")
        if image and not valid_jpeg(book_dir / image):
            return False
    return True


def cover_page_href(fetcher: Fetcher, book_id) -> str:
    """The show-in-iframe HTML's ``/en/v0/stories/{slug}/pages/{pageId}`` href."""
    iframe = fetcher.get_text(f"{SITE_BASE}/stories/show-in-iframe/{book_id}")
    m = re.search(r"""href=['"](/en/v0/stories/[^'"]+/pages/\d+)['"]""", iframe)
    if not m:
        raise RuntimeError(f"no pages href in show-in-iframe for {book_id}")
    return m.group(1)


def page_source_urls(fetcher: Fetcher, book_id) -> list[dict[str, str]]:
    """Per numbered page (book order): ``sizeN`` -> image url from the payload.

    Same parse chain as :func:`download_book`, one cached XHR per book. Text-only
    numbered pages yield ``{}`` (no illustration). End-matter blocks (credits /
    back-cover art) are excluded exactly as during download.
    """
    href = cover_page_href(fetcher, book_id)
    raw = fetcher.get_text(f"{SITE_BASE}{href}", headers=XHR_HEADERS)
    html_doc = extract_reader_html(raw)
    out: list[dict[str, str]] = []
    for container in split_page_containers(html_doc):
        if not container_is_story_page(container):
            continue
        out.append(container_image_size_urls(container))
    return out


def download_jpeg(fetcher: Fetcher, url: str, dest: Path) -> None:
    """Fetch one image unless dest already holds a valid JPEG (resume-tolerant)."""
    if valid_jpeg(dest):
        return
    dest.write_bytes(fetcher.get_bytes(url))


def download_book(
    fetcher: Fetcher,
    book_id: int,
    shelf_order: int,
    out_root: Path,
    meta_lpp: dict[int, int | None],
) -> dict:
    """Ingest one book. Returns the report row dict (also used by validation)."""
    book_dir = out_root / str(book_id)
    warnings: list[str] = []

    # 1) metadata (always fetched -- page-count validation needs lastPagePosition)
    data = fetcher.get_json(story_url(book_id)).get("data") or {}
    try:
        meta_lpp[book_id] = int(data.get("lastPagePosition"))
    except (TypeError, ValueError):
        meta_lpp[book_id] = None

    if book_complete(book_dir):
        existing = json.loads((book_dir / "book.json").read_text(encoding="utf-8"))
        text_pages = sum(1 for p in existing.get("pages") or [] if (p.get("text") or "").strip())
        return {
            "id": book_id,
            "title": existing.get("title") or "",
            "pages": existing.get("pageCount") or 0,
            "bytes": sum(p.stat().st_size for p in sorted(book_dir.iterdir()) if p.is_file()),
            "text_pages": text_pages,
            "skipped": True,
            "warnings": warnings,
        }

    book_dir.mkdir(parents=True, exist_ok=True)

    # 2) cover page id + 3) the one XHR payload with every page
    href = cover_page_href(fetcher, book_id)
    raw = fetcher.get_text(f"{SITE_BASE}{href}", headers=XHR_HEADERS)
    html_doc = extract_reader_html(raw)

    # 4) split into page blocks; keep the NUMBERED pages (fc front cover +
    #    sp story pages) == metadata lastPagePosition == the payload's own
    #    page_number "N/M" sequence. bic/bc credits + back-cover blocks are
    #    unnumbered end-matter: their text is preserved VERBATIM in
    #    `attribution` (and is not part of pages[]).
    containers = split_page_containers(html_doc)
    pages: list[dict] = []
    end_matter = 0
    end_matter_imaged = 0
    text_only_pages: list[int] = []
    for container in containers:
        if not container_is_story_page(container):
            end_matter += 1
            if container_image_url(container):
                end_matter_imaged += 1
            continue
        img_url = container_image_url(container)
        n = len(pages) + 1
        if img_url is None:
            # numbered text-only page (payload has no illustration for it)
            text_only_pages.append(n)
        pages.append(
            {
                "n": n,
                "image": f"page-{n:02d}.jpg" if img_url else "",
                "text": container_content_texts(container),
                "_url": img_url,
            }
        )
    if not pages:
        raise RuntimeError(f"{book_id}: no numbered pages found in payload")
    if end_matter:
        warnings.append(
            f"{end_matter} credits/back-cover end-matter block(s) captured in attribution "
            f"(not numbered pages)"
        )
    if end_matter_imaged:
        warnings.append(
            f"{end_matter_imaged} end-matter block(s) carry an illustration in the payload "
            f"(back-cover art, not a numbered page; not downloaded)"
        )
    for n in text_only_pages:
        warnings.append(f"page {n} is a numbered text-only page (no image in payload)")

    # 5) attribution (verbatim credits, tags stripped) + year
    attribution = extract_attribution(html_doc)
    copyright_notice = str(data.get("copyrightNotice") or "")
    published_year, year_src = parse_published_year(
        attribution, copyright_notice, str(data.get("publishedDate") or "")
    )
    if not published_year:
        warnings.append("publishedYear unavailable")

    # 6) images: thumb + page-NN.jpg (size7), skipping already-valid files
    thumb_url = cover_thumb_url(data)
    if thumb_url:
        download_jpeg(fetcher, thumb_url, book_dir / "thumb.jpg")
    else:
        warnings.append("no cover thumb url in metadata")
    for page in pages:
        if page["_url"]:
            download_jpeg(fetcher, page["_url"], book_dir / page["image"])
    # drop stale page images left over from a previous (differently-parsed) run
    referenced = {p["image"] for p in pages if p["image"]} | {"thumb.jpg"}
    for stale in sorted(book_dir.glob("page-*.jpg")):
        if stale.name not in referenced:
            stale.unlink()

    # 7) book.json (exact schema)
    slug = str(data.get("slug") or "")
    book_json = {
        "id": int(book_id),
        "title": str(data.get("name") or ""),
        "slug": slug,
        "sourceUrl": f"{SITE_BASE}/en/stories/{slug}",
        "language": str(data.get("language") or ""),
        "level": int(data.get("level") or 0),
        "orientation": str(data.get("orientation") or ""),
        "pageCount": len(pages),
        "license": LICENSE,
        "licenseUrl": LICENSE_URL,
        "attribution": attribution,
        "copyrightNotice": copyright_notice,
        "publisher": str((data.get("publisher") or {}).get("name") or ""),
        "publishedYear": published_year,
        "authors": name_list(data.get("authors")),
        "illustrators": name_list(data.get("illustrators")),
        "shelfOrder": shelf_order,
        "pages": [{"n": p["n"], "image": p["image"], "text": p["text"]} for p in pages],
    }
    (book_dir / "book.json").write_text(
        json.dumps(book_json, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )

    text_pages = sum(1 for p in pages if p["text"])
    return {
        "id": book_id,
        "title": book_json["title"],
        "pages": len(pages),
        "bytes": sum(p.stat().st_size for p in sorted(book_dir.iterdir()) if p.is_file()),
        "text_pages": text_pages,
        "skipped": False,
        "warnings": warnings,
    }


def validate_library(
    out_root: Path,
    rows: list[dict],
    meta_lpp: dict[int, int | None],
) -> tuple[list[str], list[str]]:
    """Full validation pass. Returns (errors, warnings); errors => fail loudly."""
    errors: list[str] = []
    warnings: list[str] = []
    for row in rows:
        book_id = row["id"]
        book_dir = out_root / str(book_id)
        label = f"book {book_id}"
        try:
            data = json.loads((book_dir / "book.json").read_text(encoding="utf-8"))
        except (OSError, ValueError) as err:
            errors.append(f"{label}: book.json unreadable: {err}")
            continue

        pages = data.get("pages") or []
        page_count = data.get("pageCount")
        # pageCount == number of pages; image files == pages that reference one
        images_on_disk = sorted(book_dir.glob("page-*.jpg"))
        referenced = [str(p.get("image") or "") for p in pages]
        referenced_files = [r for r in referenced if r]
        if page_count != len(pages):
            errors.append(f"{label}: pageCount {page_count} != {len(pages)} pages in book.json")
        if len(referenced_files) != len(images_on_disk):
            errors.append(
                f"{label}: {len(referenced_files)} image refs in book.json != "
                f"{len(images_on_disk)} page-*.jpg on disk"
            )
        lpp = meta_lpp.get(book_id)
        if lpp is not None and page_count != lpp:
            errors.append(f"{label}: pageCount {page_count} != metadata lastPagePosition {lpp}")

        # every JPEG: FFD8 magic + > 2KB (thumb + referenced pages)
        jpegs = [book_dir / "thumb.jpg"] + [book_dir / r for r in referenced_files]
        for jpg in jpegs:
            if not jpg.exists():
                errors.append(f"{label}: missing {jpg.name}")
            elif not jpg.read_bytes().startswith(JPEG_MAGIC):
                errors.append(f"{label}: {jpg.name} does not start with FFD8")
            elif jpg.stat().st_size <= JPEG_MIN_BYTES:
                errors.append(f"{label}: {jpg.name} is <= 2KB ({jpg.stat().st_size} bytes)")

        # attribution: non-empty + license-aware wording + the year
        attribution = str(data.get("attribution") or "")
        year = str(data.get("publishedYear") or "")
        license_name = str(data.get("license") or "")
        if not attribution.strip():
            errors.append(f"{label}: attribution is empty")
        else:
            if license_name.startswith("CC BY"):
                if "CC BY" not in attribution:
                    errors.append(f"{label}: attribution does not contain 'CC BY'")
            elif license_name == "Public Domain":
                if "public domain" not in attribution.lower():
                    errors.append(f"{label}: attribution does not contain 'public domain'")
            else:
                errors.append(f"{label}: unsupported license {license_name!r}")
            if not year:
                errors.append(f"{label}: publishedYear is missing")
            elif year not in attribution:
                errors.append(f"{label}: attribution does not contain the year {year}")

        # at least 4 pages of non-empty text (report-only)
        text_pages = sum(1 for p in pages if (p.get("text") or "").strip())
        if text_pages < 4:
            warnings.append(f"{label} ({data.get('title')}): only {text_pages} page(s) with text")
    return errors, warnings


