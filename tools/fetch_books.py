AUDIO_NAME_RE = re.compile(r"^page-(\d+)\.(mp3|wav)$")


def scan_book_audio(book_dir: Path) -> dict[int, str]:
    """Disk truth: page number -> book-relative ``audio/page-NN.{mp3,wav}``.

    Canonical zero-padded ``page-{n:02d}`` names win over other digit
    paddings; ``mp3`` wins over ``wav`` at equal names.
    """
    audio_dir = book_dir / "audio"
    found: dict[int, tuple[tuple[int, int], str]] = {}
    if not audio_dir.is_dir():
        return {}
    for path in sorted(audio_dir.iterdir()):
        match = AUDIO_NAME_RE.match(path.name)
        if not match or not path.is_file():
            continue
        n = int(match.group(1))
        prio = (
            0 if match.group(1) == f"{n:02d}" else 1,
            0 if match.group(2) == "mp3" else 1,
        )
        if n not in found or prio < found[n][0]:
            found[n] = (prio, f"audio/{path.name}")
    return {n: rel for n, (_prio, rel) in found.items()}


def cmd_audio(args: argparse.Namespace) -> int:
    """Stamp/unstamp book.json ``pages[].audio``, then run the manifest path.

    Stamping is driven by the ``audio/page-NN.{mp3,wav}`` files on disk (the
    outputs of ``tools/fetch_audio.py``): each matching page gets its relative
    ``audio`` path, stale ``audio`` fields whose files are gone are removed,
    and nothing else in book.json is touched. Manifest + CREDITS are then
    regenerated through the SAME code path ``manifest`` uses.
    """
    books_root = Path(args.out)
    if not books_root.is_dir():
        print(f"error: library books dir not found: {books_root}", file=sys.stderr)
        return 2
    stamped = removed = 0
    rows: list[str] = []
    for bj_path in sorted(books_root.glob("*/book.json")):
        book_dir = bj_path.parent
        try:
            data = json.loads(bj_path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as err:
            print(f"error: book {book_dir.name}: book.json unreadable: {err}",
                  file=sys.stderr)
            return 1
        found = scan_book_audio(book_dir)
        changed = False
        book_stamped = book_removed = 0
        for page in data.get("pages") or []:
            n = int(page.get("n") or 0)
            has_field = "audio" in page
            current = page.get("audio")
            current_ok = (
                has_field and bool(current) and (book_dir / str(current)).is_file()
            )
            if current_ok:
                continue  # stamped and present: leave it untouched
            want = found.get(n)
            if want is None:
                if has_field:
                    del page["audio"]  # stale: the file is gone
                    changed = True
                    book_removed += 1
            elif not has_field or current != want:
                page["audio"] = want
                changed = True
                book_stamped += 1
        if not changed:
            continue
        bj_path.write_text(
            json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
        stamped += book_stamped
        removed += book_removed
        rows.append(
            f"book {book_dir.name}: stamped {book_stamped}, removed {book_removed}"
        )

    print("== fetch_books.py audio -- stamp report ==")
    for row in rows or ["no book.json changes"]:
        print(f"  {row}")
    print(f"totals: stamped {stamped} field(s), removed {removed} field(s)")
    print()
    return cmd_manifest(args)


