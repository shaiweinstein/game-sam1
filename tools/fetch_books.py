def cmd_download(args: argparse.Namespace) -> int:
    ids = parse_id_list(args.ids)
    if not ids:
        print("error: --ids produced an empty id list", file=sys.stderr)
        return 2
    out_root = Path(args.out)
    out_root.mkdir(parents=True, exist_ok=True)

    fetcher = Fetcher(use_cache=not args.no_cache)
    print(f"== fetch_books.py download: {len(ids)} books -> {out_root} ==", file=sys.stderr)

    rows: list[dict] = []
    meta_lpp: dict[int, int | None] = {}
    for shelf_order, book_id in enumerate(ids, start=1):
        print(f"[{shelf_order:02d}/{len(ids):02d}] book {book_id} ...",
              end=" ", file=sys.stderr, flush=True)
        try:
            row = download_book(fetcher, book_id, shelf_order, out_root, meta_lpp)
        except Exception as err:  # keep going; validation reports the hole loudly
            meta_lpp.setdefault(book_id, None)
            row = {
                "id": book_id,
                "title": f"FAILED: {err}",
                "pages": 0,
                "bytes": 0,
                "text_pages": 0,
                "skipped": False,
                "warnings": [f"download failed: {err}"],
            }
            print("FAILED", file=sys.stderr)
        else:
            state = "resumed" if row["skipped"] else f"{row['pages']} pages, {row['bytes']:,} B"
            print(state, file=sys.stderr)
        row["shelfOrder"] = shelf_order
        rows.append(row)

    # ordered shelf index (raw; the manifest task comes later)
    index = []
    for row in rows:
        bj_path = out_root / str(row["id"]) / "book.json"
        if not bj_path.exists():
            continue
        try:
            data = json.loads(bj_path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        index.append(
            {
                "id": data.get("id"),
                "shelfOrder": row["shelfOrder"],
                "title": data.get("title"),
                "level": data.get("level"),
                "pageCount": data.get("pageCount"),
                "path": str(row["id"]),
            }
        )
    (out_root / "index.json").write_text(
        json.dumps(index, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )

    errors, warnings = validate_library(out_root, rows, meta_lpp)
    for row in rows:
        if not (out_root / str(row["id"]) / "book.json").exists():
            errors.append(f"book {row['id']}: download failed, no book.json")

    print_report(rows, errors, warnings)
    print(f"bytes fetched      : {fetcher.stats()}")
    return 1 if errors else 0


