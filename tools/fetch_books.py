#!/usr/bin/env python3
"""StoryWeaver book ingest for the lily-game library shelf (stdlib only).

Pratham Books / StoryWeaver content is CC BY 4.0. This CLI gathers a curation
shortlist so the PM can pick 18 titles for the in-game library shelf.

Subcommands
-----------
candidates
    Page through the StoryWeaver ``books-search`` JSON API (no auth), filter
    client-side for English level 1-3 non-GIF storybooks of a usable length,
    and write a shortlist to:

    * /tmp/kilo/book-candidates.json  -- machine list (~40 candidates)
    * /tmp/kilo/book-candidates.md    -- human table + excluded notable titles

download
    Fetch a curated shelf of books into ``library/books/{id}/`` (stdlib only):

    * ``thumb.jpg``            -- storycard cover thumb (metadata size1 url)
    * ``page-01.jpg`` ...      -- size7 page images in book order
    * ``book.json``            -- metadata + per-page text + CC BY attribution
    * ``library/books/index.json`` -- raw ordered shelf index

    Ingest chain (live-verified): ``/api/v1/stories/{id}`` metadata (title is
    under ``name``; ``lastPagePosition`` = page count) -> cover page id from
    ``/stories/show-in-iframe/{id}`` -> ONE XHR GET of
    ``/en/v0/stories/{slug}/pages/{pageId}`` returning the whole book as a
    JS-string-escaped HTML payload (unescape ``\\"`` first, then ``\\'``, then
    ``\\/``, ONLY THEN run HTML regexes). Page blocks carry
    ``responsive_illustration`` images (download ``data-size7-src``) and
    ``content``/``newStories`` textboxes; unimaged credits/back-cover blocks
    supply the verbatim attribution text (CC BY 4.0). Resume-tolerant: a book
    with a valid ``book.json`` and all valid JPEGs is skipped on re-runs.

manifest
    Regenerate the catalog/attribution artifacts from the ``book.json`` files
    already on disk (no network, deterministic -- no timestamps in output):

    * ``library/manifest.json``       -- the game's shelf catalog (all paths
      relative to ``library/``, books sorted by ``shelfOrder`` from book.json)
    * ``library/CREDITS.md``          -- the CC BY attribution sheet: one entry
      per book (standard CC BY pattern + the verbatim ``attribution`` text)
    * ``THIRD-PARTY-NOTICES.md``      -- the StoryWeaver section is appended at
      the end; re-runs replace that section in place (idempotent, never
      duplicated)

reimage
    Data-fix pass over an already-downloaded shelf: every ``page-*.jpg`` larger
    than 300KB (300 * 1024 B) is replaced by the next smaller CDN variant of
    the SAME illustration crop -- ``.../illustration_crops/{crop}/size7/{hash}.jpg``
    -> ``size6`` -> ``size5`` -- chosen per page: start at size7; if the result
    would exceed 300KB drop to size6; if still over 300KB drop to size5; if
    STILL over 300KB keep size5 and warn. Files at/under the cap are never
    touched (old-era ~117KB size7 pages stay byte-identical), ``thumb.jpg``
    stays size1, and ``book.json`` is not modified (it stores no byte sizes).
    Page source URLs are re-derived from the cached pages payload per book
    (one small XHR per book, cache-warm = zero network).

audio
    Stamp/unstamp the page-narration audio fields (clips generated by
    ``tools/fetch_audio.py``): scan ``library/books/*/audio/page-NN.{mp3,wav}``
    and set each book.json ``pages[].audio`` to the book-relative path (e.g.
    ``audio/page-02.mp3``); stale ``audio`` fields whose files are gone are
    removed and nothing else in book.json is touched. Then regenerate
    manifest + CREDITS through the SAME code path ``manifest`` uses (no forked
    writers). A book carrying any ``audio`` gains one CREDITS.md line
    crediting Xiaomi MiMo TTS (idempotent upsert).

Network policy
--------------
Sequential GETs only, polite User-Agent, 20 s timeout, one retry, and every
response is cached under /tmp/kilo/fetch-books-cache/ so an interrupted run
resumes without re-fetching (pass ``--no-cache`` to force fresh reads).
"""

