def probe_levels_filter(fetcher: Fetcher) -> tuple[dict[str, int], bool | None]:
    """Compare metadata.hits for levels[]=1/2/3/4 vs unfiltered.

    Returns (hits_by_label, filters?) where filters is True if ``levels[]``
    visibly changes hits, False if it is ignored, None if undecidable.
    """
    hits: dict[str, int] = {}
    for level in ("1", "2", "3", "4"):
        payload = fetcher.get_json(search_url(1, 1, levels=[level]))
        hits[level] = int((payload.get("metadata") or {}).get("hits") or -1)
    payload = fetcher.get_json(search_url(1, 1, levels=None))
    hits["all"] = int((payload.get("metadata") or {}).get("hits") or -1)

    level_hits = [hits[k] for k in ("1", "2", "3", "4")]
    filters: bool | None
    if hits["all"] <= 0 or any(h < 0 for h in level_hits):
        filters = None
    elif all(h == hits["all"] for h in level_hits):
        filters = False  # param ignored: every level returns the full hit count
    elif len(set(level_hits)) > 1 and all(h <= hits["all"] for h in level_hits):
        filters = True
    else:
        filters = None
    return hits, filters


def collect_search_pool(fetcher: Fetcher, min_english: int) -> tuple[list[dict], dict]:
    """Page books-search (Most Read) until >= min_english English books, deduped."""
    requested = 100
    first = fetcher.get_json(search_url(1, requested))
    rows0 = first.get("data") or []
    hits = int((first.get("metadata") or {}).get("hits") or 0)

    # per_page=100 is "accepted" only if we actually get 100 rows while more
    # hits exist; otherwise the server capped the page size (e.g. at 24).
    if 0 < len(rows0) < requested and hits > len(rows0):
        per_page = len(rows0)
    else:
        per_page = requested

    pool: dict = {}

    def ingest(rows: list[dict]) -> None:
        for book in rows:
            book_id = book.get("id")
            if book_id is not None and book_id not in pool:
                pool[book_id] = book

    def english_count() -> int:
        return sum(1 for b in pool.values() if b.get("language") == "English")

    ingest(rows0)
    page = 1
    max_pages = MAX_SEARCH_PAGES
    if per_page > 0 and hits > 0:
        max_pages = min(MAX_SEARCH_PAGES, (min(hits, 10000) + per_page - 1) // per_page)

    while english_count() < min_english and page < max_pages:
        page += 1
        payload = fetcher.get_json(search_url(page, per_page))
        rows = payload.get("data") or []
        if not rows:
            break
        ingest(rows)

    notes = {"hits": hits, "per_page": per_page, "pages_fetched": page}
    return list(pool.values()), notes


def client_filter(books: list[dict]) -> tuple[list[dict], list[dict]]:
    """language == English, level in {1,2,3}, not a GIF.

    Returns (eligible, dropped) where dropped entries carry a drop reason.
    (The API caps hits at 10000 and honors params only partially, so this
    client-side pass is mandatory even when the query already filtered.)
    """
    eligible: list[dict] = []
    dropped: list[dict] = []
    for book in books:
        language = str(book.get("language") or "")
        level = level_of(book)
        if language != "English":
            dropped.append(describe_drop(book, f"language={language or '?'}"))
        elif is_gif(book):
            dropped.append(describe_drop(book, "gif"))
        elif level == "4":
            dropped.append(describe_drop(book, "level 4"))
        elif level not in ALLOWED_LEVELS:
            dropped.append(describe_drop(book, f"level={level or '?'}"))
        else:
            eligible.append(book)
    eligible.sort(key=reads_of, reverse=True)
    return eligible, dropped


def fetch_page_count(fetcher: Fetcher, book_id) -> int | None:
    """Per-story metadata: lastPagePosition is the book's page count."""
    try:
        payload = fetcher.get_json(story_url(book_id))
    except RuntimeError as err:
        print(f"  ! metadata failed for {book_id}: {err}", file=sys.stderr)
        return None
    data = payload.get("data") or {}
    try:
        return int(data.get("lastPagePosition"))
    except (TypeError, ValueError):
        return None


def apply_page_filter(
    fetcher: Fetcher,
    eligible: list[dict],
    meta_limit: int,
    final_target: int,
) -> tuple[list[dict], list[dict], int]:
    """Fetch page counts for the top-N by reads, keep MIN_PAGES..MAX_PAGES.

    Only the top ``meta_limit`` books (grown by META_FETCH_BATCH up to
    META_FETCH_HARD_CAP if the shortlist runs short) get a per-story metadata
    fetch -- page counts are not knowable any cheaper. Returns
    (finalists_in_reads_order, dropped_with_reason, metadata_fetches).
    """
    finalists: list[dict] = []
    dropped: list[dict] = []
    fetched = 0
    window = min(meta_limit, len(eligible))

    def inspect(book: dict) -> bool:
        """Fetch one book's page count; record finalist/drop. True if finalist."""
        nonlocal fetched
        pages = fetch_page_count(fetcher, book.get("id"))
        fetched += 1
        if pages is None:
            dropped.append(describe_drop(book, "page count unavailable"))
            return False
        if pages < MIN_PAGES:
            dropped.append(describe_drop(book, f"pages={pages} (under {MIN_PAGES})"))
            return False
        if pages > MAX_PAGES:
            dropped.append(describe_drop(book, f"pages={pages} (over {MAX_PAGES})"))
            return False
        book = dict(book)
        book["_pages"] = pages
        finalists.append(book)
        return True

    for book in eligible[:window]:
        inspect(book)

    while (
        len(finalists) < final_target
        and window < len(eligible)
        and window < max(meta_limit, META_FETCH_HARD_CAP)
    ):
        grow = min(META_FETCH_BATCH, len(eligible) - window)
        grow = min(grow, max(meta_limit, META_FETCH_HARD_CAP) - window)
        if grow <= 0:
            break
        for book in eligible[window : window + grow]:
            inspect(book)
        window += grow

    return finalists, dropped, fetched


