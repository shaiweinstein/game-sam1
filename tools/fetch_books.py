def derive_themes(*texts: str | None) -> str:
    """Return up to two keyword-derived theme labels, or '' if nothing matches."""
    blob = " ".join(t.lower() for t in texts if t)
    blob = re.sub(r"[^a-z0-9\s]", " ", blob)
    scored: list[tuple[int, str]] = []
    for theme, words in THEME_KEYWORDS:
        score = 0
        for word in words:
            if re.search(r"\b" + re.escape(word) + r"\b", blob):
                score += 1
        if score:
            scored.append((score, theme))
    scored.sort(key=lambda pair: (-pair[0], pair[1]))
    return ", ".join(theme for _, theme in scored[:2])


def describe_drop(book: dict, reason: str) -> dict:
    return {
        "id": book.get("id"),
        "title": book.get("title") or "",
        "reads": reads_of(book),
        "reason": reason,
    }


