def file_digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def reimage_book(fetcher: Fetcher, book_dir: Path) -> dict:
    """Downgrade this book's oversized page JPEGs via the CDN ladder.

    Only ``page-*.jpg`` files referenced by ``book.json`` and larger than
    ``REIMAGE_MAX_BYTES`` are candidates; everything else is never written.
    Returns the report row (before/after bytes + per-step counters).
    """
    warnings: list[str] = []
    book_id = int(book_dir.name) if book_dir.name.isdigit() else book_dir.name
    meta = json.loads((book_dir / "book.json").read_text(encoding="utf-8"))
    pages = meta.get("pages") or []
    before_bytes = sum(p.stat().st_size for p in sorted(book_dir.iterdir()) if p.is_file())

    # Public-domain (Project Gutenberg) books have no StoryWeaver CDN sources;
    # never resolve their ids against storyweaver.org.in.
    if str(meta.get("license") or "") != LICENSE:
        return {
            "id": book_id,
            "title": str(meta.get("title") or ""),
            "pages": len(pages),
            "before_bytes": before_bytes,
            "after_bytes": before_bytes,
            "over": 0,
            "to_size6": 0,
            "to_size5": 0,
            "still_over": 0,
            "kept_same": 0,
            "changed": [],
            "warnings": [
                "skipped: not a StoryWeaver (CC BY 4.0) book — no CDN sources"
            ],
        }

    # per-page size7..size1 urls from the (cached) one-call pages payload
    urls: list[dict[str, str]] | None
    try:
        urls = page_source_urls(fetcher, book_id)
    except Exception as err:  # keep the book untouched on any payload problem
        warnings.append(f"pages payload unavailable ({err}); book not re-imaged")
        urls = None
    if urls is not None and len(urls) != len(pages):
        warnings.append(
            f"payload has {len(urls)} numbered pages != book.json {len(pages)}; "
            f"book not re-imaged"
        )
        urls = None

    over = to_size6 = to_size5 = still_over = kept_same = 0
    changed: list[str] = []
    for page in pages:
        image = str(page.get("image") or "")
        if not image:
            continue  # numbered text-only page (e.g. book 7's page 9) -- no file
        dest = book_dir / image
        if not dest.exists():
            warnings.append(f"{image}: referenced by book.json but missing on disk")
            continue
        current = dest.read_bytes()
        if len(current) <= REIMAGE_MAX_BYTES:
            continue  # under the cap: never touched (old-era size7 is fine as-is)
        over += 1
        if urls is None:
            continue
        try:
            idx = int(page.get("n") or 0) - 1
        except (TypeError, ValueError):
            idx = -1
        sizes = urls[idx] if 0 <= idx < len(urls) else {}
        src = sizes.get("size7") or sizes.get("size6") or sizes.get("size5") or ""
        if not src:
            warnings.append(f"{image}: over cap but no source url in the payload")
            continue

        # Per-page rule: start at size7 (== current bytes, already known over the
        # cap here); drop to size6 while the result would exceed 300KB; floor at
        # size5 -- keep size5 (and warn) even if it is still over 300KB.
        variant_label = "size7"
        variant = current
        for label in REIMAGE_LADDER[1:]:
            vurl = sizes.get(label) or size_variant_url(src, label)
            if vurl is None:
                warnings.append(f"{image}: cannot derive a {label} url from {src}")
                break
            blob = fetcher.get_bytes(vurl)
            variant_label, variant = label, blob
            if len(blob) <= REIMAGE_MAX_BYTES:
                break
        if variant_label == "size7":
            kept_same += 1  # ladder derivation failed; nothing fetched
            continue
        if len(variant) > REIMAGE_MAX_BYTES:
            still_over += 1
            warnings.append(
                f"{image}: still over 300KB at {variant_label} "
                f"({len(variant):,} bytes); kept {variant_label}"
            )
        if not (variant.startswith(JPEG_MAGIC) and len(variant) > JPEG_MIN_BYTES):
            warnings.append(f"{image}: {variant_label} variant is not a valid JPEG; kept current bytes")
            kept_same += 1
            continue
        if len(variant) >= len(current):
            warnings.append(f"{image}: {variant_label} variant not smaller; kept current bytes")
            kept_same += 1
            continue
        dest.write_bytes(variant)  # same filename, same crop, smaller ladder step
        changed.append(image)
        if variant_label == "size6":
            to_size6 += 1
        else:
            to_size5 += 1

    after_bytes = sum(p.stat().st_size for p in sorted(book_dir.iterdir()) if p.is_file())
    return {
        "id": book_id,
        "title": str(meta.get("title") or ""),
        "pages": len(pages),
        "before_bytes": before_bytes,
        "after_bytes": after_bytes,
        "over": over,
        "to_size6": to_size6,
        "to_size5": to_size5,
        "still_over": still_over,
        "kept_same": kept_same,
        "changed": changed,
        "warnings": warnings,
    }


