def cmd_reimage(args: argparse.Namespace) -> int:
    out_root = Path(args.out)
    if not out_root.is_dir():
        print(f"error: library dir not found: {out_root}", file=sys.stderr)
        return 2
    book_dirs = sorted(
        (d for d in out_root.iterdir() if d.is_dir() and (d / "book.json").exists()),
        key=lambda d: (0, int(d.name)) if d.name.isdigit() else (1, d.name),
    )
    if not book_dirs:
        print(f"error: no book dirs with book.json under {out_root}", file=sys.stderr)
        return 2

    fetcher = Fetcher(use_cache=not args.no_cache)
    print(f"== fetch_books.py reimage: {len(book_dirs)} books in {out_root} ==", file=sys.stderr)
    print(f"cap: page-*.jpg over {REIMAGE_MAX_BYTES:,} B (300KB) drop size7 -> size6 -> size5",
          file=sys.stderr)

    # before-snapshot (size + sha256) of every file: proves what stayed untouched
    before: dict[Path, tuple[int, str]] = {}
    for book_dir in book_dirs:
        for f in sorted(book_dir.iterdir()):
            if f.is_file():
                data = f.read_bytes()
                before[f] = (len(data), hashlib.sha256(data).hexdigest())

    rows: list[dict] = []
    for i, book_dir in enumerate(book_dirs, start=1):
        print(f"[{i:02d}/{len(book_dirs):02d}] book {book_dir.name} ...",
              end=" ", file=sys.stderr, flush=True)
        try:
            row = reimage_book(fetcher, book_dir)
        except Exception as err:
            row = {
                "id": book_dir.name,
                "title": f"FAILED: {err}",
                "pages": 0,
                "before_bytes": 0,
                "after_bytes": 0,
                "over": 0,
                "to_size6": 0,
                "to_size5": 0,
                "still_over": 0,
                "kept_same": 0,
                "changed": [],
                "warnings": [f"reimage failed: {err}"],
            }
            print("FAILED", file=sys.stderr)
        else:
            delta = row["before_bytes"] - row["after_bytes"]
            print(
                f"{len(row['changed'])} page(s) replaced, saved {delta:,} B"
                if row["changed"]
                else "untouched",
                file=sys.stderr,
            )
        rows.append(row)

    # confirmations over the full before/after snapshot
    small_pages = small_pages_changed = 0
    other_files_changed = 0
    for path, (size, digest) in before.items():
        after_digest = file_digest(path) if path.exists() else None
        changed = after_digest != digest
        is_page = path.name.startswith("page-") and path.suffix == ".jpg"
        if is_page and size <= REIMAGE_MAX_BYTES:
            small_pages += 1
            if changed:
                small_pages_changed += 1
        elif not is_page or size <= REIMAGE_MAX_BYTES:
            if changed:
                other_files_changed += 1
    final_total = sum(
        p.stat().st_size for d in book_dirs for p in d.iterdir() if p.is_file()
    ) + (out_root / "index.json").stat().st_size
    confirmations = {
        "small_pages": small_pages,
        "small_pages_changed": small_pages_changed,
        "other_files_changed": other_files_changed,
        "final_total_mib": f"{final_total / (1024.0 * 1024.0):.2f}",
        "final_total_ok": final_total <= 20 * 1024 * 1024,
    }

    # same validation pass as download (meta_lpp unknown here -> lpp check skipped)
    errors, warnings = validate_library(out_root, rows, {})
    for row in rows:
        if not (out_root / str(row["id"]) / "book.json").exists():
            errors.append(f"book {row['id']}: book.json missing")

    print_reimage_report(rows, errors, warnings, confirmations)
    print(f"bytes fetched      : {fetcher.stats()}")
    return 1 if errors else 0


